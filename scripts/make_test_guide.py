"""
make_test_guide.py — writes docs/review/test_guide.md from the tests themselves.

Run from the repository root:   python scripts/make_test_guide.py

For every test file it lists the file's purpose (first line of its docstring), how many tests it holds, and the
"Shows:" sentence of the tests that have one — the sentences meant to be read out in the review
("how this is useful"). Nothing is imported or executed; the files are only read.
"""
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TESTS = ROOT / "tests"
OUTPUT = ROOT / "docs" / "review" / "test_guide.md"
LAYERS = [
    ("unit", "Unit tests", "One function or class at a time. Everything outside it is replaced by a small fake."),
    ("integration", "Integration tests",
     "Several real modules working together (HTTP routes, SQL, the agent loop). Only PostgreSQL, Redis, Gmail, "
     "the embedding model and the LLM are faked."),
    ("system", "System tests",
     "One whole user journey through the app, for example a page visit that ends as a cited answer."),
]


def first_line(text: str) -> str:
    return " ".join((text or "").strip().splitlines()[0].split()) if (text or "").strip() else ""


def describe(path: Path) -> tuple[str, int, list[tuple[str, str]]]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    purpose = first_line(ast.get_docstring(tree) or "")
    tests, shows = 0, []
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
            tests += 1
            doc = ast.get_docstring(node) or ""
            for line in doc.splitlines():
                if line.strip().startswith("Shows"):
                    shows.append((node.name, " ".join(line.strip().split())))
    return purpose, tests, shows


def main() -> None:
    lines = ["# What the tests show", "",
             "Generated by `python scripts/make_test_guide.py` from the test files. Each *Shows* line is a sentence "
             "to say in the review: what the test proves and why that matters.", ""]
    grand_total = 0
    for folder, title, blurb in LAYERS:
        files = sorted((TESTS / folder).glob("test_*.py"))
        counts = [describe(path) for path in files]
        total = sum(count for _, count, _ in counts)
        grand_total += total
        lines += [f"## {title} — {total} tests in {len(files)} files", "", blurb, ""]
        for path, (purpose, count, shows) in zip(files, counts):
            lines.append(f"### `tests/{folder}/{path.name}` — {count} tests")
            if purpose:
                lines.append(f"{purpose}")
            lines.append("")
            for name, sentence in shows:
                lines.append(f"- `{name}` — {sentence}")
            if shows:
                lines.append("")
    lines.insert(4, f"**{grand_total} tests in total** (parametrised tests count once per function here; "
                    "pytest runs each parameter set separately).", )
    lines.insert(5, "")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {grand_total} test functions")


if __name__ == "__main__":
    main()
